import {build} from 'esbuild';
import {readFile,writeFile} from 'node:fs/promises';
const output='shop-reference-hero-20261025.js';
const result=await build({entryPoints:['shop-hero-runtime.js'],bundle:true,format:'esm',target:'es2022',minify:true,write:false,legalComments:'none'});
const source='// Generated by tools/build-shop-hero.mjs; edit shop-hero-runtime.js.\n'+result.outputFiles[0].text;
if(process.argv.includes('--check')){if(await readFile(output,'utf8')!==source)throw Error('Shop hero bundle is stale. Run node tools/build-shop-hero.mjs');}
else await writeFile(output,source);
console.log('Shop hero bundle verified ('+Buffer.byteLength(source)+' bytes)');
