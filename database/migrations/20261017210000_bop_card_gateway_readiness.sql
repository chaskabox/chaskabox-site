-- BOP card gateway: future-ready controls and ledger only.
-- NO card acceptance, no card checkout method, no gateway credentials, no existing order updates.
CREATE TABLE public.card_gateway_control (
 id boolean PRIMARY KEY DEFAULT true CHECK(id=true),
 provider text NOT NULL DEFAULT 'bop' CHECK(provider='bop'),
 enabled boolean NOT NULL DEFAULT false,
 integration_verified boolean NOT NULL DEFAULT false,
 settlement_days integer CHECK(settlement_days IS NULL OR settlement_days BETWEEN 0 AND 120),
 fee_bps integer CHECK(fee_bps IS NULL OR fee_bps BETWEEN 0 AND 10000),
 fixed_fee_pkr integer CHECK(fixed_fee_pkr IS NULL OR fixed_fee_pkr BETWEEN 0 AND 100000),
 updated_at timestamptz NOT NULL DEFAULT now(),
 updated_by uuid,
 CONSTRAINT card_enabled_requires_verified_integration CHECK(NOT enabled OR integration_verified)
);
INSERT INTO public.card_gateway_control(id,provider,enabled,integration_verified)
 VALUES(true,'bop',false,false);
-- Transactions are populated ONLY by a future verified gateway server webhook.
-- No PAN, CVV, expiry date, PIN, bank account number or secrets are stored.
CREATE TABLE public.card_gateway_transactions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 provider text NOT NULL DEFAULT 'bop' CHECK(provider='bop'),
 order_id uuid REFERENCES public.orders(id) ON DELETE RESTRICT,
 provider_transaction_id text NOT NULL CHECK(length(btrim(provider_transaction_id)) BETWEEN 4 AND 120),
 status text NOT NULL CHECK(status IN('initiated','authorized','captured','settled','failed','refunded','chargeback')),
 gross_amount_pkr integer NOT NULL CHECK(gross_amount_pkr>0),
 fee_amount_pkr integer NOT NULL DEFAULT 0 CHECK(fee_amount_pkr>=0),
 net_settled_pkr integer NOT NULL DEFAULT 0 CHECK(net_settled_pkr>=0),
 provider_created_at timestamptz NOT NULL,
 settled_on date,
 settlement_reference text,
 updated_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT card_net_bounded CHECK(fee_amount_pkr+net_settled_pkr<=gross_amount_pkr),
 CONSTRAINT card_settlement_evidence CHECK((status<>'settled') OR (settled_on IS NOT NULL AND
   settlement_reference IS NOT NULL AND length(btrim(settlement_reference)) BETWEEN 3 AND 120))
);
CREATE UNIQUE INDEX card_gateway_transaction_provider_ref ON public.card_gateway_transactions(provider,provider_transaction_id);
CREATE INDEX card_gateway_transactions_order_idx ON public.card_gateway_transactions(order_id);
CREATE INDEX card_gateway_transactions_status_idx ON public.card_gateway_transactions(status);
ALTER TABLE public.card_gateway_control ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.card_gateway_transactions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.card_gateway_control, public.card_gateway_transactions FROM PUBLIC,anon,authenticated;
GRANT SELECT,INSERT,UPDATE ON public.card_gateway_control TO service_role;
GRANT SELECT,INSERT,UPDATE ON public.card_gateway_transactions TO service_role;
GRANT USAGE,SELECT ON SEQUENCE public.card_gateway_transactions_id_seq TO service_role;

-- Staff can store fee/settlement estimates, or disable the switch at any time.
-- ON remains blocked until a separate audited BOP integration has been verified
-- and the API confirms live credentials and actual payment processing readiness.
CREATE FUNCTION public.admin_card_gateway_update(
 p_actor uuid,p_enabled boolean,p_settlement_days integer,
 p_fee_bps integer,p_fixed_fee_pkr integer
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE v_role text; v_before jsonb; v_row public.card_gateway_control;
BEGIN
 SELECT role INTO v_role FROM public.admin_roles WHERE user_id=p_actor AND active FOR SHARE;
 IF v_role IS NULL OR v_role<>'owner' THEN
  RETURN jsonb_build_object('error','Only an active owner can change card gateway settings','status',403);
 END IF;
 IF p_enabled IS NULL OR
 (p_settlement_days IS NOT NULL AND p_settlement_days NOT BETWEEN 0 AND 120) OR
 (p_fee_bps IS NOT NULL AND p_fee_bps NOT BETWEEN 0 AND 10000) OR
 (p_fixed_fee_pkr IS NOT NULL AND p_fixed_fee_pkr NOT BETWEEN 0 AND 100000) THEN
  RETURN jsonb_build_object('error','Invalid card configuration','status',400);
 END IF;
 SELECT to_jsonb(g) INTO v_before FROM public.card_gateway_control g WHERE id=true FOR UPDATE;
 IF NOT FOUND THEN RETURN jsonb_build_object('error','Card gateway not provisioned','status',503); END IF;
 IF p_enabled AND NOT COALESCE((v_before->>'integration_verified')::boolean,false) THEN
  RETURN jsonb_build_object('error','BOP card gateway not integrated or verified yet. Card payments remain disabled.','status',409);
 END IF;
 UPDATE public.card_gateway_control SET enabled=p_enabled,settlement_days=p_settlement_days,
 fee_bps=p_fee_bps,fixed_fee_pkr=p_fixed_fee_pkr,updated_by=p_actor,updated_at=now()
 WHERE id=true RETURNING * INTO v_row;
 INSERT INTO public.audit_log(actor_id,actor_role,action,entity_type,entity_id,before_data,after_data)
 VALUES(p_actor,v_role,'payment.card_gateway_settings_updated','card_gateway','bop',v_before,to_jsonb(v_row));
 RETURN jsonb_build_object('gateway',to_jsonb(v_row));
END $$;
REVOKE ALL ON FUNCTION public.admin_card_gateway_update(uuid,boolean,integer,integer,integer) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.admin_card_gateway_update(uuid,boolean,integer,integer,integer) TO service_role;
