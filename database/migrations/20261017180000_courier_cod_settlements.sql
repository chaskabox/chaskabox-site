-- Courier assignment and expected COD remittance. Server-only tables/RPCs.
-- Existing orders retain their original totals/statuses; no guessed courier backfill.
CREATE TABLE IF NOT EXISTS public.courier_companies (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name text NOT NULL CHECK(length(btrim(name)) BETWEEN 2 AND 100),
 settlement_days integer NOT NULL CHECK(settlement_days BETWEEN 0 AND 120),
 deduction_per_order_pkr integer NOT NULL DEFAULT 0 CHECK(deduction_per_order_pkr BETWEEN 0 AND 100000),
 is_active boolean NOT NULL DEFAULT true,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS courier_companies_name_ci ON public.courier_companies(lower(name));
CREATE TABLE IF NOT EXISTS public.courier_order_shipments (
 order_id uuid PRIMARY KEY REFERENCES public.orders(id) ON DELETE RESTRICT,
 courier_id bigint NOT NULL REFERENCES public.courier_companies(id) ON DELETE RESTRICT,
 courier_name_snapshot text NOT NULL,
 tracking_number text,
 settlement_days_snapshot integer NOT NULL CHECK(settlement_days_snapshot BETWEEN 0 AND 120),
 deduction_snapshot_pkr integer NOT NULL CHECK(deduction_snapshot_pkr BETWEEN 0 AND 100000),
 assigned_at timestamptz NOT NULL DEFAULT now(),
 assigned_by uuid NOT NULL
);
CREATE INDEX IF NOT EXISTS courier_shipments_courier_idx ON public.courier_order_shipments(courier_id);
CREATE TABLE IF NOT EXISTS public.courier_cod_receipts (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id uuid NOT NULL REFERENCES public.courier_order_shipments(order_id) ON DELETE RESTRICT,
 amount_pkr integer NOT NULL CHECK(amount_pkr>0),
 received_on date NOT NULL,
 reference text NOT NULL CHECK(length(btrim(reference)) BETWEEN 3 AND 120),
 recorded_by uuid NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE (order_id,reference)
);
CREATE INDEX IF NOT EXISTS courier_receipts_order_idx ON public.courier_cod_receipts(order_id);

ALTER TABLE public.courier_companies ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.courier_order_shipments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.courier_cod_receipts ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.courier_companies,public.courier_order_shipments,public.courier_cod_receipts FROM PUBLIC,anon,authenticated;
GRANT SELECT,INSERT,UPDATE,DELETE ON public.courier_companies,public.courier_order_shipments,public.courier_cod_receipts TO service_role;
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;

-- Only the service-role backend may read this ledger; courier charges are a
-- forecast, not bank-cleared cash. Delivered timestamps come from status events.
CREATE OR REPLACE VIEW public.courier_cod_ledger AS
SELECT o.id AS order_id,o.order_number,o.customer_city,o.payment_method,
 o.payment_status,o.fulfilment_status,o.total AS order_total_pkr,
 s.courier_id,s.courier_name_snapshot AS courier_name,s.tracking_number,
 s.assigned_at,s.settlement_days_snapshot AS settlement_days,
 s.deduction_snapshot_pkr AS courier_deduction_pkr,
 e.delivered_at,CASE WHEN e.delivered_at IS NOT NULL THEN
  (e.delivered_at AT TIME ZONE 'Asia/Karachi')::date+s.settlement_days_snapshot ELSE NULL END AS expected_settlement_on,
 CASE WHEN o.payment_method='cod' AND o.payment_status<>'refunded' AND o.fulfilment_status<>'cancelled'
   THEN greatest(o.total-s.deduction_snapshot_pkr,0) ELSE 0 END AS estimated_remittance_pkr,
 coalesce(p.paid_pkr,0)::bigint AS received_pkr,
 CASE WHEN o.payment_method='cod' AND o.fulfilment_status='delivered' AND o.payment_status<>'refunded'
  THEN greatest(greatest(o.total-s.deduction_snapshot_pkr,0)-coalesce(p.paid_pkr,0),0)
  ELSE 0 END AS outstanding_pkr
FROM public.courier_order_shipments s
JOIN public.orders o ON o.id=s.order_id
LEFT JOIN LATERAL (
 SELECT MIN(created_at) AS delivered_at FROM public.order_status_events
 WHERE order_id=o.id::text AND event_type='fulfilment_status' AND new_status='delivered'
) e ON true
LEFT JOIN LATERAL (
 SELECT SUM(amount_pkr) AS paid_pkr FROM public.courier_cod_receipts WHERE order_id=o.id
) p ON true;
REVOKE ALL ON public.courier_cod_ledger FROM PUBLIC,anon,authenticated;
GRANT SELECT ON public.courier_cod_ledger TO service_role;

CREATE OR REPLACE FUNCTION public.admin_courier_company_save(
 p_actor uuid,p_id bigint,p_name text,p_settlement_days integer,p_deduction_pkr integer,p_active boolean
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE v_role text; v_before jsonb; v_company public.courier_companies;
BEGIN
 SELECT role INTO v_role FROM public.admin_roles WHERE user_id=p_actor AND active FOR SHARE;
 IF v_role NOT IN ('owner','manager') OR v_role IS NULL THEN
  RETURN jsonb_build_object('error','Owner or manager required','status',403);
 END IF;
 IF p_name IS NULL OR length(btrim(p_name)) NOT BETWEEN 2 AND 100 OR p_settlement_days NOT BETWEEN 0 AND 120
  OR p_deduction_pkr NOT BETWEEN 0 AND 100000 OR p_active IS NULL THEN
  RETURN jsonb_build_object('error','Invalid courier settings','status',400);
 END IF;
 IF p_id IS NULL THEN
  INSERT INTO public.courier_companies(name,settlement_days,deduction_per_order_pkr,is_active)
  VALUES(btrim(p_name),p_settlement_days,p_deduction_pkr,p_active) RETURNING * INTO v_company;
 ELSE
  SELECT to_jsonb(c) INTO v_before FROM public.courier_companies c WHERE id=p_id FOR UPDATE;
  IF NOT FOUND THEN RETURN jsonb_build_object('error','Courier not found','status',404); END IF;
  UPDATE public.courier_companies SET name=btrim(p_name),settlement_days=p_settlement_days,
   deduction_per_order_pkr=p_deduction_pkr,is_active=p_active,updated_at=now()
   WHERE id=p_id RETURNING * INTO v_company;
 END IF;
 INSERT INTO public.audit_log(actor_id,actor_role,action,entity_type,entity_id,before_data,after_data)
 VALUES(p_actor,v_role,'courier.settings_saved','courier_company',v_company.id::text,v_before,to_jsonb(v_company));
 RETURN jsonb_build_object('courier',to_jsonb(v_company));
END $$;
REVOKE ALL ON FUNCTION public.admin_courier_company_save(uuid,bigint,text,integer,integer,boolean) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.admin_courier_company_save(uuid,bigint,text,integer,integer,boolean) TO service_role;

-- Courier assignment and packed->dispatched happen inside ONE transaction.
CREATE OR REPLACE FUNCTION public.admin_courier_dispatch(
 p_actor uuid,p_order uuid,p_courier bigint,p_tracking text DEFAULT NULL,p_expected_updated_at timestamptz DEFAULT NULL
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE v_role text; v_order public.orders; v_courier public.courier_companies; v_result jsonb;
BEGIN
 SELECT role INTO v_role FROM public.admin_roles WHERE user_id=p_actor AND active FOR SHARE;
 IF v_role IS NULL OR v_role NOT IN('owner','manager','fulfilment') THEN
  RETURN jsonb_build_object('error','Active order staff required','status',403);
 END IF;
 IF p_tracking IS NOT NULL AND (length(btrim(p_tracking))>120 OR p_tracking !~ '^[A-Za-z0-9][A-Za-z0-9 /._-]*$') THEN
  RETURN jsonb_build_object('error','Invalid tracking number','status',400);
 END IF;
 SELECT * INTO v_order FROM public.orders WHERE id=p_order FOR UPDATE;
 IF NOT FOUND THEN RETURN jsonb_build_object('error','Order not found','status',404); END IF;
 IF v_order.fulfilment_status<>'packed' THEN
  RETURN jsonb_build_object('error','Order must be packed before courier dispatch','status',409);
 END IF;
 IF p_expected_updated_at IS NOT NULL AND v_order.updated_at IS DISTINCT FROM p_expected_updated_at THEN
  RETURN jsonb_build_object('error','Order changed; reload first','status',409);
 END IF;
 IF EXISTS(SELECT 1 FROM public.courier_order_shipments WHERE order_id=p_order) THEN
  RETURN jsonb_build_object('error','Courier already assigned','status',409);
 END IF;
 SELECT * INTO v_courier FROM public.courier_companies WHERE id=p_courier AND is_active FOR SHARE;
 IF NOT FOUND THEN RETURN jsonb_build_object('error','Choose an active courier company','status',400); END IF;
 IF v_order.payment_method='cod' AND v_courier.deduction_per_order_pkr>v_order.total THEN
  RETURN jsonb_build_object('error','Courier deduction exceeds COD order total','status',400);
 END IF;
 v_result:=public.admin_order_mutate(p_actor,p_order,'status','dispatched','',p_expected_updated_at);
 IF v_result ? 'error' THEN RETURN v_result; END IF;
 INSERT INTO public.courier_order_shipments(order_id,courier_id,courier_name_snapshot,tracking_number,
 settlement_days_snapshot,deduction_snapshot_pkr,assigned_by)
 VALUES(p_order,v_courier.id,v_courier.name,NULLIF(btrim(p_tracking),''),
 v_courier.settlement_days,v_courier.deduction_per_order_pkr,p_actor);
 INSERT INTO public.audit_log(actor_id,actor_role,action,entity_type,entity_id,after_data)
 VALUES(p_actor,v_role,'courier.dispatched','order',p_order::text,
 jsonb_build_object('courier_id',v_courier.id,'courier_name',v_courier.name,
 'tracking_number',NULLIF(btrim(p_tracking),''),'settlement_days',v_courier.settlement_days,
 'deduction_pkr',v_courier.deduction_per_order_pkr));
 RETURN v_result;
END $$;
REVOKE ALL ON FUNCTION public.admin_courier_dispatch(uuid,uuid,bigint,text,timestamptz) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.admin_courier_dispatch(uuid,uuid,bigint,text,timestamptz) TO service_role;

CREATE OR REPLACE FUNCTION public.admin_courier_record_receipt(
 p_actor uuid,p_order uuid,p_amount integer,p_received_on date,p_reference text
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE v_role text; v_order public.orders; v_shipment public.courier_order_shipments;
 v_expected integer; v_paid bigint; v_receipt public.courier_cod_receipts;
BEGIN
 SELECT role INTO v_role FROM public.admin_roles WHERE user_id=p_actor AND active FOR SHARE;
 IF v_role IS NULL OR v_role NOT IN('owner','manager') THEN
  RETURN jsonb_build_object('error','Owner or manager required','status',403);
 END IF;
 IF p_amount IS NULL OR p_amount<1 OR p_received_on IS NULL OR p_received_on>(now() AT TIME ZONE 'Asia/Karachi')::date
   OR p_reference IS NULL OR length(btrim(p_reference)) NOT BETWEEN 3 AND 120 THEN
  RETURN jsonb_build_object('error','Amount, received date and bank/statement reference required','status',400);
 END IF;
 SELECT * INTO v_order FROM public.orders WHERE id=p_order FOR UPDATE;
 IF NOT FOUND OR v_order.payment_method<>'cod' OR v_order.fulfilment_status<>'delivered'
  OR v_order.payment_status='refunded' THEN
  RETURN jsonb_build_object('error','Only delivered, non-refunded COD orders can receive courier remittance','status',409);
 END IF;
 SELECT * INTO v_shipment FROM public.courier_order_shipments WHERE order_id=p_order FOR UPDATE;
 IF NOT FOUND THEN RETURN jsonb_build_object('error','Courier assignment missing','status',409); END IF;
 v_expected:=greatest(v_order.total-v_shipment.deduction_snapshot_pkr,0);
 SELECT coalesce(sum(amount_pkr),0) INTO v_paid FROM public.courier_cod_receipts WHERE order_id=p_order;
 IF v_paid+p_amount>v_expected THEN
  RETURN jsonb_build_object('error','Receipt exceeds outstanding expected remittance','status',409);
 END IF;
 IF EXISTS(SELECT 1 FROM public.courier_cod_receipts WHERE order_id=p_order AND lower(reference)=lower(btrim(p_reference))) THEN
  RETURN jsonb_build_object('error','This receipt reference is already recorded','status',409);
 END IF;
 INSERT INTO public.courier_cod_receipts(order_id,amount_pkr,received_on,reference,recorded_by)
 VALUES(p_order,p_amount,p_received_on,btrim(p_reference),p_actor) RETURNING * INTO v_receipt;
 INSERT INTO public.audit_log(actor_id,actor_role,action,entity_type,entity_id,after_data)
 VALUES(p_actor,v_role,'courier.cod_received','order',p_order::text,
 jsonb_build_object('receipt_id',v_receipt.id,'amount_pkr',p_amount,'received_on',p_received_on,
 'reference',btrim(p_reference),'courier_id',v_shipment.courier_id));
 RETURN jsonb_build_object('receipt',to_jsonb(v_receipt),'outstanding_pkr',v_expected-v_paid-p_amount);
END $$;
REVOKE ALL ON FUNCTION public.admin_courier_record_receipt(uuid,uuid,integer,date,text) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.admin_courier_record_receipt(uuid,uuid,integer,date,text) TO service_role;
