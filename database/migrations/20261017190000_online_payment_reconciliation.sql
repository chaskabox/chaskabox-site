-- Online payment reconciliation alongside courier COD. No checkout/card enablement.
-- No existing order or historic payment status is mutated by this migration.
CREATE TABLE public.online_payment_accounts (
 method text PRIMARY KEY CHECK(method IN('jazzcash','bank_transfer')),
 display_name text NOT NULL CHECK(length(btrim(display_name)) BETWEEN 2 AND 60),
 account_label text CHECK(account_label IS NULL OR length(btrim(account_label)) BETWEEN 2 AND 100),
 settlement_days integer CHECK(settlement_days IS NULL OR settlement_days BETWEEN 0 AND 120),
 updated_at timestamptz NOT NULL DEFAULT now()
);
INSERT INTO public.online_payment_accounts(method,display_name,account_label,settlement_days)
VALUES ('jazzcash','JazzCash',NULL,NULL),('bank_transfer','Bank Transfer',NULL,NULL);
-- Card gateways require a separate real provider integration before activation.

CREATE TABLE public.online_payment_receipts (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id uuid NOT NULL REFERENCES public.orders(id) ON DELETE RESTRICT,
 amount_pkr integer NOT NULL CHECK(amount_pkr > 0),
 processing_fee_pkr integer NOT NULL DEFAULT 0 CHECK(processing_fee_pkr >= 0),
 received_on date NOT NULL,
 reference text NOT NULL CHECK(length(btrim(reference)) BETWEEN 3 AND 120),
 recorded_by uuid NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX online_payment_receipts_order_idx ON public.online_payment_receipts(order_id);
CREATE UNIQUE INDEX online_payment_receipts_unique_ref_ci ON public.online_payment_receipts(order_id,lower(btrim(reference)));
ALTER TABLE public.online_payment_accounts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.online_payment_receipts ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.online_payment_accounts,public.online_payment_receipts FROM PUBLIC,anon,authenticated;
GRANT SELECT ON public.online_payment_accounts,public.online_payment_receipts TO service_role;
GRANT INSERT,UPDATE,DELETE ON public.online_payment_accounts,public.online_payment_receipts TO service_role;
GRANT USAGE,SELECT ON SEQUENCE public.online_payment_receipts_id_seq TO service_role;

-- A VERIFIED customer transaction and merchant payout/bank deposit are separate
-- facts. Neither verification nor a projected date generates a cash receipt.
CREATE VIEW public.online_payment_ledger AS
SELECT o.id AS order_id,o.order_number,o.payment_method,o.payment_status,
 o.fulfilment_status,o.total AS order_total_pkr,o.transaction_reference,
 o.created_at,p.display_name,p.account_label,p.settlement_days,
 e.verified_at,
 CASE WHEN e.verified_at IS NOT NULL AND p.settlement_days IS NOT NULL
  THEN (e.verified_at AT TIME ZONE 'Asia/Karachi')::date+p.settlement_days ELSE NULL END AS expected_settlement_on,
 CASE WHEN o.payment_status='payment_verified' AND o.fulfilment_status<>'cancelled'
  THEN o.total ELSE 0 END AS verified_gross_pkr,
 COALESCE(r.received_pkr,0)::bigint AS received_pkr,
 COALESCE(r.processing_fees_pkr,0)::bigint AS processing_fees_pkr,
 CASE WHEN o.payment_status='payment_verified' AND o.fulfilment_status<>'cancelled' THEN
  GREATEST(o.total-COALESCE(r.received_pkr,0)-COALESCE(r.processing_fees_pkr,0),0)
 ELSE 0 END AS unreconciled_pkr
FROM public.orders o
JOIN public.online_payment_accounts p ON p.method=o.payment_method
LEFT JOIN LATERAL (
 SELECT MIN(created_at) AS verified_at
 FROM public.order_status_events
 WHERE order_id=o.id::text AND event_type='payment_status' AND new_status='payment_verified'
) e ON true
LEFT JOIN LATERAL (
 SELECT SUM(amount_pkr) received_pkr,SUM(processing_fee_pkr) processing_fees_pkr
 FROM public.online_payment_receipts WHERE order_id=o.id
) r ON true;
REVOKE ALL ON public.online_payment_ledger FROM PUBLIC,anon,authenticated;
GRANT SELECT ON public.online_payment_ledger TO service_role;

CREATE FUNCTION public.admin_online_payment_account_save(
 p_actor uuid,p_method text,p_label text,p_days integer
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE v_role text; v_account public.online_payment_accounts; v_before jsonb;
BEGIN
 SELECT role INTO v_role FROM public.admin_roles WHERE user_id=p_actor AND active FOR SHARE;
 IF v_role IS NULL OR v_role NOT IN('owner','manager') THEN
  RETURN jsonb_build_object('error','Owner or manager required','status',403);
 END IF;
 IF p_method NOT IN('jazzcash','bank_transfer') OR
 (p_label IS NOT NULL AND length(btrim(p_label)) NOT BETWEEN 2 AND 100) OR
 (p_days IS NOT NULL AND p_days NOT BETWEEN 0 AND 120) THEN
  RETURN jsonb_build_object('error','Invalid online payment account settings','status',400);
 END IF;
 SELECT to_jsonb(a) INTO v_before FROM public.online_payment_accounts a WHERE method=p_method FOR UPDATE;
 IF NOT FOUND THEN RETURN jsonb_build_object('error','Unsupported payment method','status',400); END IF;
 UPDATE public.online_payment_accounts
 SET account_label=NULLIF(btrim(p_label),''),
     settlement_days=p_days,updated_at=now()
 WHERE method=p_method RETURNING * INTO v_account;
 INSERT INTO public.audit_log(actor_id,actor_role,action,entity_type,entity_id,before_data,after_data)
 VALUES(p_actor,v_role,'payment.account_settings_saved','online_payment_account',p_method,v_before,to_jsonb(v_account));
 RETURN jsonb_build_object('account',to_jsonb(v_account));
END $$;
REVOKE ALL ON FUNCTION public.admin_online_payment_account_save(uuid,text,text,integer) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.admin_online_payment_account_save(uuid,text,text,integer) TO service_role;

CREATE FUNCTION public.admin_online_payment_record_receipt(
 p_actor uuid,p_order uuid,p_amount integer,p_fee integer,p_received_on date,p_reference text
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE v_role text; v_order public.orders; v_paid bigint; v_fees bigint;
 v_receipt public.online_payment_receipts;
BEGIN
 SELECT role INTO v_role FROM public.admin_roles WHERE user_id=p_actor AND active FOR SHARE;
 IF v_role IS NULL OR v_role NOT IN('owner','manager') THEN
  RETURN jsonb_build_object('error','Owner or manager required','status',403);
 END IF;
 IF p_amount IS NULL OR p_amount<=0 OR p_fee IS NULL OR p_fee<0 OR
 p_received_on IS NULL OR p_received_on>(now() AT TIME ZONE 'Asia/Karachi')::date OR
 p_reference IS NULL OR length(btrim(p_reference)) NOT BETWEEN 3 AND 120 THEN
  RETURN jsonb_build_object('error','Valid payout, fee, date and unique bank/wallet statement reference required','status',400);
 END IF;
 SELECT * INTO v_order FROM public.orders WHERE id=p_order FOR UPDATE;
 IF NOT FOUND OR v_order.payment_method NOT IN ('jazzcash','bank_transfer')
  OR v_order.payment_status<>'payment_verified' OR v_order.fulfilment_status='cancelled' THEN
  RETURN jsonb_build_object('error','Only independently verified, non-cancelled online orders can be reconciled','status',409);
 END IF;
 SELECT COALESCE(SUM(amount_pkr),0),COALESCE(SUM(processing_fee_pkr),0)
 INTO v_paid,v_fees FROM public.online_payment_receipts WHERE order_id=p_order;
 IF v_paid+v_fees+p_amount+p_fee>v_order.total THEN
  RETURN jsonb_build_object('error','Payout and fees exceed the verified order total','status',409);
 END IF;
 IF EXISTS(SELECT 1 FROM public.online_payment_receipts
    WHERE order_id=p_order AND lower(btrim(reference))=lower(btrim(p_reference))) THEN
  RETURN jsonb_build_object('error','Statement reference already recorded for this order','status',409);
 END IF;
 INSERT INTO public.online_payment_receipts(order_id,amount_pkr,processing_fee_pkr,received_on,reference,recorded_by)
 VALUES(p_order,p_amount,p_fee,p_received_on,btrim(p_reference),p_actor) RETURNING * INTO v_receipt;
 INSERT INTO public.audit_log(actor_id,actor_role,action,entity_type,entity_id,after_data)
 VALUES(p_actor,v_role,'payment.online_payout_received','order',p_order::text,
  jsonb_build_object('receipt_id',v_receipt.id,'amount_pkr',p_amount,'processing_fee_pkr',p_fee,
    'received_on',p_received_on,'reference',btrim(p_reference),'method',v_order.payment_method));
 RETURN jsonb_build_object('receipt',to_jsonb(v_receipt),'unreconciled_pkr',v_order.total-v_paid-v_fees-p_amount-p_fee);
END $$;
REVOKE ALL ON FUNCTION public.admin_online_payment_record_receipt(uuid,uuid,integer,integer,date,text) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.admin_online_payment_record_receipt(uuid,uuid,integer,integer,date,text) TO service_role;
