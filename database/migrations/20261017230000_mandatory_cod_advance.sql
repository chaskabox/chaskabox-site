-- Snapshot the setting at order creation: later owner switches affect only new orders.
CREATE FUNCTION public.snapshot_cod_advance() RETURNS trigger
 LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
DECLARE v_enabled boolean; v_amount integer;
BEGIN
 IF NEW.payment_method<>'cod' THEN NEW.cod_advance_required_pkr:=0; RETURN NEW; END IF;
 SELECT coalesce((SELECT (value#>>'{}')::boolean FROM public.site_settings WHERE key='cod_advance_enabled'),true) INTO v_enabled;
 SELECT coalesce((SELECT (value#>>'{}')::integer FROM public.site_settings WHERE key='cod_advance_amount_pkr'),500) INTO v_amount;
 IF v_amount NOT BETWEEN 1 AND 100000 THEN RAISE EXCEPTION 'Invalid COD advance setting'; END IF;
 NEW.cod_advance_required_pkr:=CASE WHEN v_enabled THEN least(NEW.total,v_amount) ELSE 0 END;
 RETURN NEW;
END $$;
CREATE TRIGGER cod_advance_snapshot_before_order
 BEFORE INSERT ON public.orders FOR EACH ROW EXECUTE FUNCTION public.snapshot_cod_advance();

