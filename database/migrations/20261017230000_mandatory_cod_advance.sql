-- Even internal order mutations cannot mark new COD orders packed/dispatch/delivered
-- until an authenticated staff member has recorded verified advance receipts.
CREATE FUNCTION public.require_cod_advance_before_dispatch() RETURNS trigger
 LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
DECLARE v_received bigint;
BEGIN
 IF OLD.cod_advance_required_pkr IS DISTINCT FROM NEW.cod_advance_required_pkr
 THEN RAISE EXCEPTION 'COD advance snapshot is immutable'; END IF;
 IF NEW.fulfilment_status IS DISTINCT FROM OLD.fulfilment_status AND
    NEW.fulfilment_status IN('packed','dispatched','delivered') AND
    NEW.payment_method='cod' AND NEW.cod_advance_required_pkr>0 THEN
  SELECT coalesce(sum(amount_pkr),0) INTO v_received FROM public.cod_advance_receipts WHERE order_id=NEW.id;
  IF v_received<NEW.cod_advance_required_pkr THEN
   RAISE EXCEPTION 'COD_ADVANCE_UNPAID: Verify required COD advance before packing or dispatch';
  END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER require_cod_advance_for_fulfilment
 BEFORE UPDATE OF fulfilment_status,cod_advance_required_pkr ON public.orders
 FOR EACH ROW EXECUTE FUNCTION public.require_cod_advance_before_dispatch();

CREATE OR REPLACE FUNCTION public.checkout_quote(p_order jsonb)
 RETURNS jsonb LANGUAGE sql SET search_path='' AS $$
 SELECT q.quote||jsonb_build_object(
  'cod_advance_required_pkr',CASE WHEN p_order->>'payment_method'='cod' AND
   coalesce((SELECT (value#>>'{}')::boolean FROM public.site_settings WHERE key='cod_advance_enabled'),true)
   THEN least((q.quote->>'total')::int,coalesce((SELECT (value#>>'{}')::int
    FROM public.site_settings WHERE key='cod_advance_amount_pkr'),500)) ELSE 0 END,
  'cod_due_on_delivery_pkr',(q.quote->>'total')::int -
  CASE WHEN p_order->>'payment_method'='cod' AND
   coalesce((SELECT (value#>>'{}')::boolean FROM public.site_settings WHERE key='cod_advance_enabled'),true)
   THEN least((q.quote->>'total')::int,coalesce((SELECT (value#>>'{}')::int
    FROM public.site_settings WHERE key='cod_advance_amount_pkr'),500)) ELSE 0 END
 ) FROM (SELECT chaskabox_private.checkout_totals(p_order,false) AS quote) q
 $$;
REVOKE ALL ON FUNCTION public.checkout_quote(jsonb) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.checkout_quote(jsonb) TO service_role;

CREATE FUNCTION public.admin_cod_advance_record(
 p_actor uuid,p_order uuid,p_amount integer,p_channel text,p_reference text,p_received_on date
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE v_role text; v_order public.orders; v_paid bigint; v_receipt public.cod_advance_receipts;
BEGIN
 SELECT role INTO v_role FROM public.admin_roles WHERE user_id=p_actor AND active FOR SHARE;
 IF v_role IS NULL OR v_role NOT IN('owner','manager') THEN
  RETURN jsonb_build_object('error','Owner/manager must independently verify the payment','status',403);
 END IF;
 IF p_amount IS NULL OR p_amount<1 OR p_channel NOT IN('jazzcash','bank_transfer') OR
 p_reference IS NULL OR length(btrim(p_reference)) NOT BETWEEN 3 AND 120 OR
 p_received_on IS NULL OR p_received_on>(now() AT TIME ZONE 'Asia/Karachi')::date THEN
  RETURN jsonb_build_object('error','Enter verified payment channel, amount, date and statement reference','status',400);
 END IF;
 SELECT * INTO v_order FROM public.orders WHERE id=p_order FOR UPDATE;
 IF NOT FOUND OR v_order.payment_method<>'cod' OR v_order.cod_advance_required_pkr=0 OR
 v_order.fulfilment_status IN('cancelled','delivered') THEN
  RETURN jsonb_build_object('error','No outstanding eligible COD advance for this order','status',409);
 END IF;
 SELECT coalesce(sum(amount_pkr),0) INTO v_paid FROM public.cod_advance_receipts WHERE order_id=p_order;
 IF v_paid+p_amount>v_order.cod_advance_required_pkr THEN
  RETURN jsonb_build_object('error','Advance receipt exceeds required advance','status',409);
 END IF;
 IF EXISTS (SELECT 1 FROM public.cod_advance_receipts
     WHERE order_id=p_order AND lower(btrim(reference))=lower(btrim(p_reference))) THEN
  RETURN jsonb_build_object('error','Advance payment reference already used for this order','status',409);
 END IF;
 INSERT INTO public.cod_advance_receipts(order_id,amount_pkr,channel,reference,received_on,recorded_by)
 VALUES(p_order,p_amount,p_channel,btrim(p_reference),p_received_on,p_actor) RETURNING * INTO v_receipt;
 INSERT INTO public.audit_log(actor_id,actor_role,action,entity_type,entity_id,after_data)
 VALUES(p_actor,v_role,'payment.cod_advance_verified','order',p_order::text,
 jsonb_build_object('receipt_id',v_receipt.id,'channel',p_channel,'amount_pkr',p_amount,
  'reference',btrim(p_reference),'received_on',p_received_on));
 RETURN jsonb_build_object('receipt',to_jsonb(v_receipt),'received_pkr',v_paid+p_amount,
 'remaining_advance_pkr',v_order.cod_advance_required_pkr-v_paid-p_amount,
 'cod_due_on_delivery_pkr',v_order.total-v_order.cod_advance_required_pkr);
END $$;
REVOKE ALL ON FUNCTION public.admin_cod_advance_record(uuid,uuid,integer,text,text,date) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.admin_cod_advance_record(uuid,uuid,integer,text,text,date) TO service_role;

-- Same net COD amount must flow to the courier ledger, otherwise courier
-- receivables are overstated by the verified customer advance.
CREATE OR REPLACE VIEW public.courier_cod_ledger AS
SELECT o.id AS order_id,o.order_number,o.customer_city,o.payment_method,
 o.payment_status,o.fulfilment_status,o.total AS order_total_pkr,
 s.courier_id,s.courier_name_snapshot AS courier_name,s.tracking_number,
 s.assigned_at,s.settlement_days_snapshot AS settlement_days,
 s.deduction_snapshot_pkr AS courier_deduction_pkr,
 e.delivered_at,CASE WHEN e.delivered_at IS NOT NULL THEN
  (e.delivered_at AT TIME ZONE 'Asia/Karachi')::date+s.settlement_days_snapshot ELSE NULL END AS expected_settlement_on,
 CASE WHEN o.payment_method='cod' AND o.payment_status<>'refunded' AND o.fulfilment_status<>'cancelled'
   THEN greatest(o.total-o.cod_advance_required_pkr-s.deduction_snapshot_pkr,0) ELSE 0 END AS estimated_remittance_pkr,
 coalesce(p.paid_pkr,0)::bigint AS received_pkr,
 CASE WHEN o.payment_method='cod' AND o.fulfilment_status='delivered' AND o.payment_status<>'refunded'
  THEN greatest(greatest(o.total-o.cod_advance_required_pkr-s.deduction_snapshot_pkr,0)-coalesce(p.paid_pkr,0),0)
  ELSE 0 END AS outstanding_pkr
FROM public.courier_order_shipments s
JOIN public.orders o ON o.id=s.order_id
LEFT JOIN LATERAL (
 SELECT MIN(created_at) AS delivered_at FROM public.order_status_events
 WHERE order_id=o.id::text AND event_type='fulfilment_status' AND new_status='delivered'
) e ON true
LEFT JOIN LATERAL (
 SELECT SUM(amount_pkr) AS paid_pkr FROM public.courier_cod_receipts WHERE order_id=o.id
) p ON true;

REVOKE ALL ON public.courier_cod_ledger FROM PUBLIC,anon,authenticated;
GRANT SELECT ON public.courier_cod_ledger TO service_role;
