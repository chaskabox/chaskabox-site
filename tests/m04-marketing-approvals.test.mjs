import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';
const m01=await readFile(new URL('../database/migrations/20261014200000_m01_agent_infrastructure.sql',import.meta.url),'utf8');
const m04=await readFile(new URL('../database/migrations/20261014230000_m04_marketing_draft_approvals.sql',import.meta.url),'utf8');
const owner='00000000-0000-4000-8000-000000000001',stranger='00000000-0000-4000-8000-000000000002';
async function fixture(){
 const db=new PGlite();
 try{
  await db.exec('CREATE ROLE anon;CREATE ROLE authenticated;CREATE ROLE service_role BYPASSRLS;');
  await db.exec("CREATE TABLE products(id bigint primary key,name text,visibility text,stock_state text,updated_at timestamptz); CREATE TABLE admin_roles(user_id uuid,role text,active boolean);CREATE TABLE audit_log(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,actor_id uuid,actor_role text,action text,entity_type text,entity_id text,before_data jsonb,after_data jsonb,created_at timestamptz default now());");
  await db.exec("INSERT INTO products VALUES(5,'Crunchy Snacks','visible','sourced_after_order',now()),(6,'Private Product','hidden','unavailable',now()); INSERT INTO admin_roles VALUES('"+owner+"','owner',true),('"+stranger+"','manager',true);");
  await db.exec(m01); await db.exec(m04);
  return db;
 }catch(e){await db.close();throw e}
}
async function call(db,actor,sql,args){
 await db.exec('SET ROLE '+actor);
 try{return (await db.query(sql,args)).rows[0].value;}
 finally{await db.exec('RESET ROLE');}
}
test('M04 only service role can read/propose/decide marketing drafts',async()=>{
 const db=await fixture();try{
  for(const r of ['anon','authenticated']){
   await assert.rejects(call(db,r,'SELECT agent_m04_list() value'),/permission denied/i);
   await assert.rejects(call(db,r,"SELECT agent_m04_propose('"+owner+"',5,'social') value"),/permission denied/i);
  }
  assert.equal((await db.query("SELECT count(*)::int n FROM chaskabox_agents.marketing_drafts")).rows[0].n,0);
 }finally{await db.close()}
});
test('M04 owner can propose exactly one safe draft; decision audited, never sends or publishes',async()=>{
 const db=await fixture();try{
  const q='SELECT agent_m04_propose($1,5,$2) value';
  await assert.rejects(call(db,'service_role',q,[stranger,'social']),/Owner role required/);
  await assert.rejects(call(db,'service_role',q,[owner,'unknown']),/Invalid marketing proposal/);
  await assert.rejects(call(db,'service_role','SELECT agent_m04_propose($1,6,$2) value',[owner,'social']),/Only currently available/);
  const first=await call(db,'service_role',q,[owner,'social']);
  const replay=await call(db,'service_role',q,[owner,'social']);
  assert.equal(first.id,replay.id);
  assert.equal(first.decision,'pending');
  assert.match(first.draft_text,/price and availability at checkout/);
  assert.doesNotMatch(first.draft_text,/free delivery|guarantee|discount/i);
  const decided=await call(db,'service_role','SELECT agent_m04_decide($1,$2::uuid,$3) value',[owner,first.id,'approved']);
  assert.deepEqual([decided.decision,decided.published,decided.sent],['approved',false,false]);
  await assert.rejects(call(db,'service_role','SELECT agent_m04_decide($1,$2::uuid,$3) value',[owner,first.id,'rejected']),/Draft not pending/);
  const audits=(await db.query('SELECT count(*)::int n FROM audit_log')).rows[0].n;
  assert.equal(audits,3);
  assert.equal((await db.query('SELECT count(*)::int n FROM chaskabox_agents.marketing_drafts')).rows[0].n,1);
 }finally{await db.close();}
});
test('M04 stale product disallows approval',async()=>{
 const db=await fixture();try{
  const d=await call(db,'service_role','SELECT agent_m04_propose($1,5,$2) value',[owner,'social']);
  await db.exec("UPDATE products SET updated_at=now()+interval '1 minute' WHERE id=5");
  await assert.rejects(call(db,'service_role','SELECT agent_m04_decide($1,$2::uuid,$3) value',[owner,d.id,'approved']),/Draft stale/);
 }finally{await db.close()}
});
