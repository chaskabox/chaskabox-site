async function role(db,name,sql,args=[]){await db.exec('SET ROLE '+name);try{return await db.query(sql,args);}finally{await db.exec('RESET ROLE');}}

test('Phase12 migration enforces role isolation, owner-only activation, audit and marketing lock',async()=>{
 const db=await fixture();
 try{
  const initial=(await role(db,'service_role','SELECT public.agent_phase12_state() AS s')).rows[0].s;
  assert.equal(initial.activation.length,8);assert.deepEqual(initial.observations,[]);
  assert.equal(initial.alerts.length,0);
  await role(db,'service_role','SELECT public.agent_phase12_activate($1,$2,$3)',[owner,'orders',true]);
  assert.equal((await db.query("SELECT enabled FROM chaskabox_agents.agent_settings WHERE agent_key='orders'")).rows[0].enabled,true);
  await role(db,'service_role','SELECT public.agent_phase12_activate($1,$2,$3)',[owner,'orders',true]);
  assert.equal((await db.query("SELECT count(*)::int AS n FROM audit_log WHERE action='agent.observation_set'")).rows[0].n,1);
  await assert.rejects(role(db,'service_role','SELECT public.agent_phase12_activate($1,$2,$3)',[owner,'marketing',false]),/Unsupported observation control/);
  await assert.rejects(role(db,'service_role','SELECT public.agent_phase12_activate($1,$2,$3)',[stranger,'seo',true]),/Active owner required/);
  const state=(await role(db,'service_role','SELECT public.agent_phase12_state() AS s')).rows[0].s;
  assert.equal(state.activation.find(x=>x.agent==='orders').enabled,true);
  for(const publicRole of ['anon','authenticated']){
   for(const f of ['agent_phase12_state()','agent_phase12_scan()',`agent_phase12_activate('${owner}','orders',true)`])
    await assert.rejects(role(db,publicRole,'SELECT public.'+f),/permission denied/i);
  }
 }finally{await db.close();}
});

