test('M05 isolated synthetic replay: five migrations together, 8 agents disabled, public denied',async()=>{
 const db=new PGlite();try{
  await db.exec('CREATE ROLE anon;CREATE ROLE authenticated;CREATE ROLE service_role BYPASSRLS;');
  await db.exec("CREATE TABLE products(id bigint PRIMARY KEY,name text,visibility text,stock_state text,updated_at timestamptz,seo_title text,seo_description text,image_url text); CREATE TABLE orders(created_at timestamptz,fulfilment_status text,payment_status text,payment_method text,total integer);CREATE TABLE notification_deliveries(status text,delivery_status text);CREATE TABLE ai_usage(created_at timestamptz,success boolean);CREATE TABLE funnel_events(created_at timestamptz,event text);CREATE TABLE admin_roles(user_id uuid,role text,active boolean);CREATE TABLE audit_log(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,actor_id uuid,actor_role text,action text,entity_type text,entity_id text,before_data jsonb,after_data jsonb,created_at timestamptz default now());");
  for(const t of ['api_rate_limits','customer_notification_outbox','notification_outbox','order_status_events','product_versions'])
   await db.exec('CREATE TABLE '+t+'(id integer);ALTER TABLE '+t+' ENABLE ROW LEVEL SECURITY;GRANT ALL ON '+t+' TO anon,authenticated,service_role;');
  await db.exec("INSERT INTO products VALUES(5,'Test Snack','visible','sourced_after_order',now(),NULL,NULL,'/images/5.webp');INSERT INTO admin_roles VALUES('"+owner+"','owner',true);");
  await db.exec('GRANT SELECT ON public.orders,public.products,public.notification_deliveries,public.ai_usage,public.funnel_events,public.admin_roles TO service_role;GRANT INSERT ON public.audit_log TO service_role;');
  for(const sql of scripts)await db.exec(sql);
  await db.exec('SET ROLE service_role');
  try{
   const state=(await db.query('SELECT agent_m01_health() state')).rows[0].state;
   assert.equal(state.agents.length,8);
   assert.equal(state.agents.every(a=>a.enabled===false),true);
   const o=(await db.query('SELECT agent_m02_order_signals() x')).rows[0].x;
   const i=(await db.query('SELECT agent_m02_inventory_signals() x')).rows[0].x;
   const s=(await db.query('SELECT agent_m03_insight_signals() x')).rows[0].x;
   const m=(await db.query('SELECT agent_m04_list() x')).rows[0].x;
   assert.equal(o.stale_new_orders,0);
   assert.equal(i.quantity_tracking_available,false);
   assert.equal(s.seo.missing_seo_title,1);
   assert.deepEqual(m,[]);
  }finally{await db.exec('RESET ROLE')}
  for(const role of ['anon','authenticated']){
   await db.exec('SET ROLE '+role);
   try{
    for(const fn of ['agent_m01_health()','agent_m02_order_signals()','agent_m03_insight_signals()','agent_m04_list()'])
     await assert.rejects(db.query('SELECT '+fn),/permission denied/i);
   }finally{await db.exec('RESET ROLE')}
  }
 }finally{await db.close()}
});
